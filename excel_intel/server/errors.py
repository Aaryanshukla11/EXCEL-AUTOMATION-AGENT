"""RFC 7807 Problem Details error models and centralized exception handlers.

Standardizes all API error responses to conform with the canonical
contract specification in FRONTEND_BACKEND_API_CONTRACT.md.
"""

from __future__ import annotations

import datetime
from typing import Any, Optional

from fastapi import FastAPI, HTTPException, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

from excel_intel.exceptions import PlatformError
from excel_intel.logging import StructuredLogger, get_logger
from excel_intel.server.admission import AdmissionRejectedError

logger: StructuredLogger = get_logger("ServerErrorHandler")


class ProblemDetails(BaseModel):
    """RFC 7807 compliant Problem Details error payload."""

    type: str = Field(
        ...,
        description="URI reference identifying the error problem type.",
    )
    title: str = Field(
        ...,
        description="Short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        ...,
        description="Human-readable explanation specific to this occurrence.",
    )
    instance: str = Field(
        ...,
        description="URI reference that identifies the specific occurrence.",
    )
    code: str = Field(
        ...,
        description="Machine-readable application error code.",
    )
    correlation_id: str = Field(
        ...,
        description="Request tracking correlation ID.",
    )
    timestamp: str = Field(
        ...,
        description="ISO 8601 UTC timestamp when the error occurred.",
    )
    invalid_params: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description="Field-level validation error details when applicable.",
    )


def _get_correlation_id(request: Request) -> str:
    """Retrieves correlation ID attached to request state or headers."""
    return getattr(request.state, "correlation_id", None) or request.headers.get(
        "X-Correlation-ID", "unknown"
    )


def _current_timestamp() -> str:
    """Returns ISO 8601 UTC timestamp."""
    return datetime.datetime.now(datetime.timezone.utc).isoformat()


async def platform_error_handler(request: Request, exc: PlatformError) -> JSONResponse:
    """Handles domain PlatformError and its subclasses."""
    correlation_id = _get_correlation_id(request)
    status_code = exc.exit_code if (100 <= exc.exit_code <= 599) else 500

    # Map category to canonical code & status if needed
    category = exc.category
    code = category.replace("ERR_", "")
    
    # Category-specific status code mapping
    if category == "ERR_CONFIG_INVALID":
        status_code = status.HTTP_400_BAD_REQUEST
        code = "INVALID_CONFIG"
    elif category == "ERR_UNSUPPORTED_FORMAT":
        status_code = status.HTTP_400_BAD_REQUEST
        code = "INVALID_FILE_TYPE"
    elif category == "ERR_CORRUPT_WORKBOOK":
        status_code = status.HTTP_400_BAD_REQUEST
        code = "CORRUPT_WORKBOOK"
    elif category == "ERR_ZIP_BOMB":
        status_code = status.HTTP_400_BAD_REQUEST
        code = "ZIP_BOMB_DETECTED"
    elif category == "ERR_SCHEMA_VIOLATION":
        status_code = status.HTTP_422_UNPROCESSABLE_ENTITY
        code = "SCHEMA_VALIDATION_ERROR"
    elif category == "ERR_FORMULA_CYCLE":
        status_code = status.HTTP_422_UNPROCESSABLE_ENTITY
        code = "FORMULA_CYCLE_DETECTED"
    elif category in ("ERR_RESOURCE_LIMIT", "ERR_RESOURCE_EXHAUSTED"):
        if status_code == 413 or exc.exit_code == 413:
            status_code = status.HTTP_413_REQUEST_ENTITY_TOO_LARGE
            code = "PAYLOAD_TOO_LARGE"
        elif exc.context.get("code") == "ZIP_BOMB_DETECTED":
            status_code = status.HTTP_400_BAD_REQUEST
            code = "ZIP_BOMB_DETECTED"
        else:
            status_code = status.HTTP_422_UNPROCESSABLE_ENTITY
            code = "INVARIANT_VIOLATION"
    elif category == "ERR_ADMISSION_REJECTED":
        status_code = status.HTTP_429_TOO_MANY_REQUESTS
        code = "ADMISSION_REJECTED"
    elif category == "ERR_IO_FAILURE":
        status_code = status.HTTP_500_INTERNAL_SERVER_ERROR
        code = "INTERNAL_DURABILITY_FAULT"

    problem = ProblemDetails(
        type=f"https://excel-intel.internal/errors/{code}",
        title=category.replace("_", " ").title(),
        status=status_code,
        detail=exc.message,
        instance=str(request.url.path),
        code=code,
        correlation_id=correlation_id,
        timestamp=_current_timestamp(),
        invalid_params=exc.context.get("invalid_params") if exc.context else None,
    )

    logger.warning(
        "PlatformErrorHandled",
        message=exc.message,
        context={
            "error_category": category,
            "status_code": status_code,
            "instance": str(request.url.path),
            "correlation_id": correlation_id,
        },
    )

    headers = {}
    if status_code == 429:
        headers["Retry-After"] = "5"

    return JSONResponse(
        status_code=status_code,
        content=problem.model_dump(exclude_none=True),
        headers=headers,
    )


async def validation_error_handler(
    request: Request, exc: RequestValidationError
) -> JSONResponse:
    """Handles FastAPI / Pydantic RequestValidationError."""
    correlation_id = _get_correlation_id(request)
    invalid_params = []
    for err in exc.errors():
        loc = " -> ".join(str(l) for l in err.get("loc", []))
        invalid_params.append({
            "name": loc,
            "reason": err.get("msg", "Validation error"),
            "type": err.get("type", "value_error"),
        })

    problem = ProblemDetails(
        type="https://excel-intel.internal/errors/SCHEMA_VALIDATION_ERROR",
        title="Schema Validation Error",
        status=status.HTTP_422_UNPROCESSABLE_ENTITY,
        detail="The request payload failed structural validation against the API schema.",
        instance=str(request.url.path),
        code="SCHEMA_VALIDATION_ERROR",
        correlation_id=correlation_id,
        timestamp=_current_timestamp(),
        invalid_params=invalid_params,
    )

    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=problem.model_dump(exclude_none=True),
    )


async def http_exception_handler(request: Request, exc: HTTPException) -> JSONResponse:
    """Handles standard Starlette / FastAPI HTTPException."""
    correlation_id = _get_correlation_id(request)

    code_map = {
        400: "INVALID_PAYLOAD",
        401: "UNAUTHENTICATED",
        403: "UNAUTHORIZED_OPERATOR",
        404: "RESOURCE_NOT_FOUND",
        409: "STATE_CONFLICT",
        422: "UNPROCESSABLE_ENTITY",
        429: "ADMISSION_REJECTED",
        500: "INTERNAL_ERROR",
        503: "SERVICE_UNAVAILABLE",
    }
    code = code_map.get(exc.status_code, "HTTP_ERROR")

    problem = ProblemDetails(
        type=f"https://excel-intel.internal/errors/{code}",
        title=code.replace("_", " ").title(),
        status=exc.status_code,
        detail=str(exc.detail),
        instance=str(request.url.path),
        code=code,
        correlation_id=correlation_id,
        timestamp=_current_timestamp(),
    )

    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        headers=getattr(exc, "headers", None),
    )


async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Fallback handler for unhandled exceptions (HTTP 500)."""
    correlation_id = _get_correlation_id(request)

    logger.error(
        "UnhandledServerException",
        message=str(exc),
        context={
            "exception_type": type(exc).__name__,
            "instance": str(request.url.path),
            "correlation_id": correlation_id,
        },
    )

    problem = ProblemDetails(
        type="https://excel-intel.internal/errors/INTERNAL_ERROR",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An unexpected internal error occurred. Please contact the administrator.",
        instance=str(request.url.path),
        code="INTERNAL_ERROR",
        correlation_id=correlation_id,
        timestamp=_current_timestamp(),
    )

    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=problem.model_dump(exclude_none=True),
    )


def register_error_handlers(app: FastAPI) -> None:
    """Registers all RFC 7807 error handlers with the FastAPI application."""
    app.add_exception_handler(PlatformError, platform_error_handler)  # type: ignore[arg-type]
    app.add_exception_handler(AdmissionRejectedError, platform_error_handler)  # type: ignore[arg-type]
    app.add_exception_handler(RequestValidationError, validation_error_handler)  # type: ignore[arg-type]
    app.add_exception_handler(HTTPException, http_exception_handler)  # type: ignore[arg-type]
    app.add_exception_handler(500, unhandled_exception_handler)
    app.add_exception_handler(Exception, unhandled_exception_handler)
